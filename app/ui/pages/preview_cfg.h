/**
 * @file preview_cfg.h
 * 预览帧管线**共用常量**（page_face 人脸识别页 / page_enroll 人脸录入页 共用）。
 *
 * 为什么单独抽头（2026-09-15 BugFix）：
 *   两页的帧管线同构（拉帧 → 旋转 → 最近邻缩放 → 查表绘制），常量也必须同源。
 *   此前 page_enroll.c 与 page_face.c 各自抄了一份常量，其中 page_face 的
 *   s_scale_max 有默认值 FACE_MAX_SCALE、page_enroll 的却漏了初始值 → 录入页
 *   放大上限恒为 0，视频矩形被夹成 1×1、预览区一片空白（用户报「录入界面不显示
 *   人脸」）。收敛到本头后两页共用同一个默认值，不会再出现「漏抄初值」的分叉。
 *   （页内帧管线整体抽成共用组件见 page_face.c 头 TODO，届时本头并入组件。）
 *
 * 纯宏头：不引入任何依赖，可被 ui 层任意页面包含，无循环包含风险。
 */
#pragma once

/* 采集分辨率：320×240（需求 v1.6 FR-16 锁定，4:3 原始比例） */
#define CAP_W  320
#define CAP_H  240

/* 拉帧周期：20fps（YUYV@320x240 实测上限 20fps） */
#define PREVIEW_MS 50

/* 画面「陈旧」判定：超过此时长没有新帧即视为无信号（占位重新显示） */
#define FACE_FRAME_STALE_MS 2500

/* 显示放大倍数上限（千分比，1300 = 1.3×）。
 * 为什么封顶：LVGL 的绘制耗时与「显示像素数」近似成正比（板上实测 223k 像素 →
 * 渲染周期 121ms ≈ 8fps；130k 像素 → 23ms ≈ 21.6fps）。而采集源固定 320×240，
 * 放大 1.3× 之后每个源像素仍被显示（1.3 个显示像素/源像素），继续放大只是最近邻
 * 复制，不增加任何细节，却线性地吃掉帧率。取 1.3× 是「画面够大」与「UI ≥20fps」
 * 的实测平衡点；面板比 416×312 还小时按面板自适应（取 min），不会过度放大。
 *
 * ⚠️ 本常量是**两页共享的默认放大上限**：使用它的静态量（s_scale_max）必须用它
 *    初始化。任一端漏初始化时值为 0，compute_video_rect() 会把视频矩形夹成 1×1，
 *    预览区变空白（2026-09-15 人脸录入页实测缺陷，勿再回归）。 */
#define FACE_MAX_SCALE 1300

/* 预览默认旋转（顺时针 0/90/180/270）：补偿摄像头在整机上的实际装配方向。
 * 2026-09-16 用户按正常姿态摆放镜头后实测：UVC 裸帧相对正方向是顺时针 90°
 * （画面里人脸倒向一侧），故默认取 270（= 逆时针 90°）把它转正。
 *   - 这是**设备的固定几何属性**，PC 与板上共用同一默认值（与 FACE_MAX_SCALE 同理，
 *     两页都必须从这里取，避免再次分叉）；
 *   - 重装/换向时用 SAFE_CAMERA_ROT 覆盖（支持显式 0），无需改代码；
 *   - 90/270 时源尺寸会换成 240×320（竖版），compute_video_rect 自动跟随。 */
#define FACE_PREVIEW_ROT_DEFAULT 270
