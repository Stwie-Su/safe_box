/**
 * @file preview_cfg.h
 * 摄像头预览的几个固定参数，人脸识别页和人脸录入页**共用这一份**。
 *
 * 为什么要共用：两个页面的预览流程一模一样（取帧 → 旋转 → 缩放 → 画到屏幕）。
 * 以前各写一份常量，录入页漏了「放大上限」的初值，结果预览区一片空白。
 * 现在统一从这里取，不会再出现两边不一致。
 *
 * 这是纯宏头，不依赖任何东西，哪个页面都能包含。
 */
#pragma once

/* 采集分辨率：320×240（4:3 原始比例）。 */
#define CAP_W  320
#define CAP_H  240

/* 多久取一帧，50ms = 20fps（320×240 下实测的上限）。 */
#define PREVIEW_MS 50

/* 超过这么久没有新帧，就当没信号，显示占位。 */
#define FACE_FRAME_STALE_MS 2500

/* 最大放大倍数（千分比，1300 = 1.3 倍）。
 * 为什么封顶：画面越大，LVGL 要画的像素越多，帧率掉得越快。
 * 采集源只有 320×240，放大 1.3 倍以后继续放大只是把像素复制得更粗，
 * 不会多出任何细节，却会线性拉低帧率。
 * ⚠️ 用到它的静态变量必须拿它初始化，否则是 0，视频区域会被夹成 1×1（预览空白）。 */
#define FACE_MAX_SCALE 1300

/* 预览默认旋转角度（0/90/180/270，顺时针），补偿摄像头的实际安装方向。
 *
 * 当前值 90 是实测出来的：先量出画面相对正方向偏了多少，再取 360 减去它。
 * ⚠️ 不要按「看起来倒了，那就转 180」这种方式直接改参数 —— 这里栽过一次。
 *    镜头重新装过或换过方向后，这个值就不对了，需要重新量。
 * 临时改角度可以用环境变量 SAFE_CAMERA_ROT，不用改代码。
 * 转 90 或 270 时画面变竖版（240×320），相关代码会自动跟着换长宽。 */
#define FACE_PREVIEW_ROT_DEFAULT 90
